// noci/optimised/space.rs
//! Excitation space of the references as standalone determinants, so that ResHF optimises the
//! orbitals of every determinant in the space and not only those of the references.

// Standard library imports.
use std::sync::Arc;

// Crate-root imports.
use crate::determinant::{NOCIIndex, NOCISpace};
use crate::input::Input;
use crate::scf::{energy, fock, occ_first};
use crate::{AoData, SCFState};

/// Every NOCI reference followed by its excitations of the `excit` orders, each as an
/// independent occupied-first determinant in its parent's orbital frame. The determinants are
/// generated by [`NOCISpace::excited_from`], so they are the same space, in the same order and
/// with the same labels, as the extended space of the post-reference methods. Each carries its
/// own densities and energy; the sign of an excitation is dropped, since a NOCI basis vector's
/// sign does not change the NOCI energies.
/// # Arguments:
/// - `ao`: Contains AO integrals and other system data.
/// - `input`: User input specifications; `excit` sets the orders.
/// - `states`: SCF states; those with `noci_basis` are the references.
/// # Returns
/// - `Vec<SCFState>`: The references and their excitations, all in the NOCI basis.
pub fn reshf_excitation_space(
    ao: &AoData,
    input: &Input,
    states: &[SCFState],
) -> Vec<SCFState> {
    let refs: Vec<SCFState> = states
        .iter()
        .filter(|st| st.noci_basis)
        .map(occ_first)
        .collect();
    let references = NOCISpace::from_scf(&refs);
    let sources: Vec<NOCIIndex> = (0..references.len()).map(NOCIIndex).collect();
    let space = references.excited_from(&sources, input, true);

    (0..space.len())
        .map(NOCIIndex)
        .map(|index| {
            // Occupy the excited orbitals of the parent frame, then rebuild the densities.
            let parent = &space.parents()[space.parent(index)];
            let (oa, ob) = space.occupations(index);
            let det = occ_first(&SCFState {
                e: parent.e,
                oa,
                ob,
                ca: Arc::clone(&parent.ca),
                cb: Arc::clone(&parent.cb),
                da: Arc::clone(&refs[space.parent(index)].da),
                db: Arc::clone(&refs[space.parent(index)].db),
                label: space.label(index).to_string(),
                noci_basis: true,
            });

            // The determinant's own energy, `E = E_{\text{nuc}} + \frac{1}{2} \mathrm{tr}((h + F) P)`.
            let (fa, fb) = fock(&ao.h, &ao.eri_coul, &det.da, &det.db);
            let e = energy(&ao.h, ao.enuc, &det.da, &det.db, &fa, &fb);
            SCFState { e, ..det }
        })
        .collect()
}
